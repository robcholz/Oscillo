// Generates src/generated.ts from include/dwf.h: every constant, the typedefs, the C prototypes koffi
// binds, and a typed interface for the raw functions. Run `npm run gen` after replacing dwf.h.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const header = readFileSync(join(root, 'include/dwf.h'), 'utf8').replace(/\r/g, '')
const obsoleteAt = header.indexOf('// OBSOLETE')

// typedef <base> <Name>;
const typedefs = new Map()
for (const m of header.matchAll(/^typedef\s+([\w ]+?)\s+(\w+)\s*;/gm)) typedefs.set(m[2], m[1].trim())

// const <Type> <name> = <value>; // comment
const consts = []
for (const m of header.matchAll(/^const\s+(\w+)\s+(\w+)\s*=\s*([^;]+);[ \t]*(?:\/\/[ \t]*(.*))?$/gm)) {
  consts.push({ type: m[1], name: m[2], value: m[3].trim(), doc: m[4]?.trim(), obsolete: m.index > obsoleteAt })
}

// DWFAPI <ret> <Name>(<params>); // comment
const funcs = []
for (const m of header.matchAll(/^DWFAPI\s+(\w+)\s+(\w+)\s*\(([^)]*)\)\s*;[ \t]*(?:\/\/[ \t]*(.*))?$/gm)) {
  const params = m[3]
    .split(',')
    .map((p) => p.trim())
    .filter((p) => p && p !== 'void')
    .map((p) => {
      const pm = /^(const\s+)?([\w ]+?)\s*(\*?)\s*(\w+)\s*(\[\d*\])?$/.exec(p.replace(/\s*\*\s*/, ' * ').replace(/\s+/g, ' '))
      if (!pm) throw new Error(`Cannot parse parameter "${p}" of ${m[2]}`)
      const [, isConst, base, star, name, arr] = pm
      return { isConst: !!isConst, base: base.trim(), pointer: !!star || !!arr, name }
    })
  funcs.push({ ret: m[1], name: m[2], params, doc: m[4]?.trim(), obsolete: m.index > obsoleteAt })
}

const resolve = (t) => {
  let x = t
  while (typedefs.has(x)) x = typedefs.get(x)
  return x
}
const ARRAYS = {
  int: 'Int32Array',
  'unsigned int': 'Uint32Array',
  double: 'Float64Array',
  'unsigned char': 'Uint8Array',
  'unsigned short': 'Uint16Array',
  short: 'Int16Array',
  'unsigned long long': 'BigUint64Array',
  char: 'Buffer',
  void: 'ArrayBufferView'
}
const tsType = (p) => {
  const base = resolve(p.base)
  if (!p.pointer) return base === 'unsigned long long' ? 'number | bigint' : 'number'
  if (p.isConst && base === 'char') return 'string'
  if (p.isConst && base === 'double') return 'Float64Array | number[]'
  const a = ARRAYS[base]
  if (!a) throw new Error(`No array type for ${p.base}`)
  return a
}
// koffi reads C prototypes; arrays become pointers and typedefs are declared as aliases.
const proto = (f) => `${f.ret} ${f.name}(${f.params.map((p) => `${p.isConst ? 'const ' : ''}${p.base}${p.pointer ? ' *' : ''} ${p.name}`).join(', ')})`

const out = []
out.push('// Generated by scripts/gen.mjs from include/dwf.h. Do not edit.', '/* eslint-disable */', '')
out.push('/** C typedefs from dwf.h, mapped to their base types. */')
out.push(`export const TYPEDEFS: Record<string, string> = ${JSON.stringify(Object.fromEntries(typedefs), null, 2)}`, '')
for (const t of typedefs.keys()) out.push(`export type ${t} = number`)
out.push('')
for (const c of consts) {
  const doc = [c.doc, c.obsolete && '@deprecated Obsolete in the SDK.'].filter(Boolean)
  if (doc.length) out.push(`/** ${doc.join(' ')} */`)
  out.push(`export const ${c.name}: ${c.type} = ${c.value}`)
}
out.push('', '/** Every SDK function as a C prototype, for koffi. */', 'export const PROTOTYPES: string[] = [')
for (const f of funcs) out.push(`  ${JSON.stringify(proto(f))},`)
out.push(']', '')
out.push('/** The SDK functions. Pointer parameters take typed arrays, written in place; each returns 1 on success. */')
out.push('export interface DwfRaw {')
for (const f of funcs) {
  const doc = [f.doc, f.obsolete && '@deprecated Obsolete in the SDK.'].filter(Boolean)
  if (doc.length) out.push(`  /** ${doc.join(' ')} */`)
  out.push(`  ${f.name}(${f.params.map((p) => `${p.name}: ${tsType(p)}`).join(', ')}): number`)
}
out.push('}', '')
writeFileSync(join(root, 'src/generated.ts'), out.join('\n'))
console.log(`dwf.h: ${funcs.length} functions, ${consts.length} constants, ${typedefs.size} typedefs`)
